def seed_recipes(db: Session, slug_map: dict[str, Ingredient]) -> int:
    """Idempotently seed the curated recipe library and calculate exact metrics."""
    created = 0
    for data in SEED_RECIPES:
        existing = db.query(Recipe).filter(Recipe.slug == data["slug"]).first()
        if existing:
            # Refresh legacy microwave instruction text on existing databases
            if "mikrowelle" in (existing.instructions_json or "").lower():
                existing.instructions_json = json.dumps(
                    data["instructions"], ensure_ascii=False
                )
            continue

        recipe = Recipe(
            slug=data["slug"],
            title=data["title"],
            description=data["description"],
            servings=data["servings"],
            prep_time_min=data["prep_time_min"],
            cook_time_min=data["cook_time_min"],
            effort_level=data["effort_level"],
            diet_type=data["diet_type"],
            meal_types_json=json.dumps(data["meal_types"], ensure_ascii=False),
            tags_json=json.dumps(data["tags"], ensure_ascii=False),
            instructions_json=json.dumps(data["instructions"], ensure_ascii=False),
            source="seed",
            image_emoji=data["image_emoji"],
        )
        db.add(recipe)
        db.flush()

        for order_idx, (ing_slug, amount, unit, prep_note) in enumerate(
            data["ingredients"]
        ):
            ing = slug_map.get(ing_slug)
            if not ing:
                raise ValueError(f"Unknown seed ingredient slug: {ing_slug}")
            ri = RecipeIngredient(
                recipe_id=recipe.id,
                ingredient_id=ing.id,
                amount=float(amount),
                unit=unit,
                preparation_note=prep_note,
                display_order=order_idx,
            )
            ri.ingredient = ing
            db.add(ri)
            recipe.ingredients.append(ri)

        recalculate_recipe_metrics(db, recipe)
        created += 1

    db.commit()
    return created
