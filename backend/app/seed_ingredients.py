def seed_stores_and_ingredients(db: Session) -> dict[str, Ingredient]:
    """Idempotently seed default stores and ALDI fundamental ingredients."""
    for chain, display_name, priority in SEED_STORES:
        existing_store = db.query(Store).filter(Store.chain == chain).first()
        if not existing_store:
            db.add(
                Store(
                    chain=chain,
                    display_name=display_name,
                    priority=priority,
                    enabled=priority <= 6,
                )
            )

    slug_map: dict[str, Ingredient] = {}
    existing_all = db.query(Ingredient).all()
    for ing in existing_all:
        slug_map[ing.slug] = ing

    for row in SEED_INGREDIENTS:
        (
            slug, name, category, unit, grams_per_unit,
            kcal, protein, carbs, sugar, fiber, fat, carb_type,
            is_staple, shelf_days, pack_size, aldi_price_eur,
            aliases, exclude_kw,
        ) = row

        if slug in slug_map:
            continue

        ing = Ingredient(
            slug=slug,
            name=name,
            category=category,
            default_unit=unit,
            grams_per_unit=grams_per_unit,
            kcal_100=kcal,
            protein_100=protein,
            carbs_100=carbs,
            sugar_100=sugar,
            fiber_100=fiber,
            fat_100=fat,
            carb_type=carb_type,
            is_pantry_staple=is_staple,
            default_shelf_life_days=shelf_days,
            default_pack_size=pack_size,
            reference_price_eur=aldi_price_eur,
            reference_price_per_base_unit=_base_unit_price(
                aldi_price_eur, pack_size, unit
            ),
            reference_store="ALDI",
            nutrition_source="bls_curated",
        )
        db.add(ing)
        db.flush()

        for alias in aliases:
            db.add(
                IngredientAlias(
                    ingredient_id=ing.id,
                    alias=alias,
                    exclude_keywords_json=json.dumps(exclude_kw, ensure_ascii=False),
                )
            )
        slug_map[slug] = ing

    db.commit()
    return slug_map
